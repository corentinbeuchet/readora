const entries = ICONS.map((name) => `  '${name}': [${shapes(readFileSync(resolve(SOURCE, `${name}.svg`), 'utf8')).map((d) => `'${d}'`).join(', ')}]`);

writeFileSync(
  TARGET,
  `// Generated by scripts/generate-icons.mjs (npm run icons) from lucide-static: don't edit by hand.
// Lucide icons, ISC licence (public/licenses/LUCIDE-ISC.txt). 24x24 grid, stroked with currentColor.
export const ICON_PATHS = {
${entries.join(',\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof ICON_PATHS;
`,
  'utf8'
);
console.log(`[icons] ${ICONS.length} icons written to ${TARGET}`);

/** Path data of every shape in an SVG file, in document order. */
function shapes(svg) {
  const found = [];
  for (const [, tag, attributes] of svg.matchAll(/<(path|circle|ellipse|line|rect|polyline|polygon)\b([^>]*?)\/?>/g)) {
    const a = Object.fromEntries([...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
    found.push(toPath(tag, a));
  }
  if (found.length === 0) throw new Error('No shape found');
  return found;
}

function toPath(tag, a) {
  const n = (key, fallback = 0) => (a[key] === undefined ? fallback : Number(a[key]));
  switch (tag) {
    case 'path':
      return a.d;
    case 'circle':
      return ellipse(n('cx'), n('cy'), n('r'), n('r'));
    case 'ellipse':
      return ellipse(n('cx'), n('cy'), n('rx'), n('ry'));
    case 'line':
      return `M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`;
    case 'polyline':
    case 'polygon': {
      const points = a.points.trim().split(/[\s,]+/).map(Number);
      const pairs = [];
      for (let i = 0; i < points.length; i += 2) pairs.push(`${points[i]} ${points[i + 1]}`);
      return `M${pairs.join('L')}${tag === 'polygon' ? 'Z' : ''}`;
    }
    case 'rect': {
      const [x, y, w, h] = [n('x'), n('y'), n('width'), n('height')];
      const rx = Math.min(n('rx', n('ry')), w / 2);
      const ry = Math.min(n('ry', n('rx')), h / 2);
      if (rx === 0 && ry === 0) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    default:
      throw new Error(`Unsupported shape <${tag}>`);
  }
}

function ellipse(cx, cy, rx, ry) {
  return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
}
